export const themeRegistry = Object.freeze([SUNNY_THEME, INK_THEME])

export const getTheme = (themeId) => (
  themeRegistry.find((theme) => theme.id === themeId) || SUNNY_THEME
)

const persistTheme = (theme) => {
  try {
    localStorage.setItem(THEME_STORAGE_KEY, JSON.stringify({
      version: THEME_CACHE_VERSION,
      id: theme.id,
      colorScheme: theme.colorScheme,
      tokens: theme.tokens,
    }))
  } catch (_) {
    // 隐私模式或存储配额不足时仍允许本次会话切换。
  }
}

export const applyTheme = (themeId, { persist = true, announce = true } = {}) => {
  const theme = getTheme(themeId)
  const root = document.documentElement

  root.dataset.theme = theme.id
  root.style.colorScheme = theme.colorScheme
  Object.entries(theme.tokens).forEach(([token, value]) => {
    root.style.setProperty(token, value)
  })

  if (persist) persistTheme(theme)
  if (announce) {
    window.dispatchEvent(new CustomEvent('blog:theme-change', { detail: { theme } }))
  }
  return theme
}

export const getStoredThemeId = () => {
  try {
    const cached = JSON.parse(localStorage.getItem(THEME_STORAGE_KEY) || 'null')
    return getTheme(cached?.id).id
  } catch (_) {
    return DEFAULT_THEME_ID
  }
}

export const initializeTheme = (themeId = getStoredThemeId()) => applyTheme(
  themeId,
  { persist: true, announce: false },
)
